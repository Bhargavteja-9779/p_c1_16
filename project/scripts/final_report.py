#!/usr/bin/env python3
"""Section 12 automatic results report (no LLM). Reads result files only; writes
results/metrics.json, results/statistics.json, tables/main_results.md and results/RESULTS_SUMMARY.md.
Every number printed here is copied from a result file named next to it. Idempotent (overwrites its outputs)."""
import csv, json, sys
from pathlib import Path
import numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def rd(p):
    p = ROOT / p
    return json.loads(p.read_text()) if p.exists() else None


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def ci(d):
    return f"{d['estimate']:.3f} [{d['ci95'][0]:.3f}, {d['ci95'][1]:.3f}]"


raw = pd.read_csv(R / "raw_results.csv")
metrics = {}
for (exp, model, fixes, split), g in raw.groupby(["experiment", "model", "fixes", "eval_split"]):
    for (tc, ec), h in g.groupby(["train_cell", "eval_cell"]):
        a = h.auroc.values
        metrics.setdefault(f"{exp}|{model}|{fixes}|{split}", {})[f"{tc}->{ec}"] = dict(
            auroc_mean=float(a.mean()), auroc_std=float(a.std(ddof=1)) if len(a) > 1 else 0.0, n_seeds=int(len(a)),
            auroc_ci95_t=[float(a.mean() - 2.776 * a.std(ddof=1) / np.sqrt(len(a))), float(a.mean() + 2.776 * a.std(ddof=1) / np.sqrt(len(a)))] if len(a) == 5 else None)
(R / "metrics.json").write_text(json.dumps(metrics, indent=1))

E6 = rd("results/analysis/E6_confirm_test.json"); E5 = rd("results/analysis/E5_E6_confirm_test.json")
V3c = rd("results/analysis/v3_confirm.json"); V3x = rd("results/analysis/v3_explore.json")
LK = rd("results/leakage_check.json"); G4 = rd("results/g4_reproduce.json"); B = rd("state/budget.json")
stats = {"E6": E6 and {"H1": E6["H1"], "H2": E6["H2"], "holm": E6["holm"]}, "v3_confirm": V3c and {"tests": V3c["tests"], "holm": V3c["holm"]}}
(R / "statistics.json").write_text(json.dumps(stats, indent=1))

L = ["# RESULTS SUMMARY (auto-generated by scripts/final_report.py from result files)\n",
     "Journal: Critical Care (journal_selection/selected_journal.md). Topic: factorial site × population transport analysis of "
     "sepsis early warning on PhysioNet 2019 (topic/selected_topic.md).\n"]
if E6:
    L += ["## Main confirmation (E6, test, seeds 100–104) — results/analysis/E6_confirm_test.json\n",
          "| model/level | gap_unit | gap_site | D = site − unit | p (boot) |", "|---|---|---|---|---|"]
    for k, v in E6["H1"].items():
        L.append(f"| {k} | {ci(v['gap_unit'])} | {ci(v['gap_site'])} | {ci(v['D'])} | {v['D']['p_boot']:.4f} |")
    L += ["", "Holm family: " + ", ".join(f"{k} p = {v['p']:.4f}, p_Holm = {v['p_holm']:.4f}" for k, v in E6["holm"].items()), ""]
if E5:
    L.append("## Label-free estimators (E5) — tables/E5_E6_confirm_test.md\n")
    L.append((ROOT / "tables/E5_E6_confirm_test.md").read_text() if (ROOT / "tables/E5_E6_confirm_test.md").exists() else "")
for name, V in (("v3 confirmation (test)", V3c), ("v3 exploration (val)", V3x)):
    if V:
        L += [f"## {name} — results/analysis/v3_{V['phase']}.json\n", "| test | estimate [95% CI] | p (boot) | p (Holm) |", "|---|---|---|---|"]
        for k, v in V["tests"].items():
            L.append(f"| {k} | {ci(v)} | {v['p_boot']:.4f} | {V['holm'][k]:.4f} |")
        L.append("")
if G4:
    L += ["## Comparison with published numbers (G4) — results/g4_reproduce.json\n",
          f"Our cohort under the published protocol: {G4['cohort_stays']} stays, {G4['events']} events (published: {G4['published']['cohort']}, {G4['published']['events']}).\n",
          "| model | source | internal AUROC | external AUROC |", "|---|---|---|---|"]
    for k, v in G4["results"].items():
        ext = [x for x in v if "to" in x][0]
        L.append(f"| {k.rsplit('_', 1)[0]} | {k.rsplit('_', 1)[1]} | {v['internal']:.3f} | {ext}: {v[ext]:.3f} |")
    p = G4["published"]
    L += [f"| XGBoost (published) | A | {p['xgb_A_int']} | AtoB: {p['xgb_AtoB']} |", f"| XGBoost (published) | B | {p['xgb_B_int']} | BtoA: {p['xgb_BtoA']} |", ""]
if LK:
    L.append(f"## Leakage check (G8): {'PASS' if LK['PASS'] else 'FAIL'} — results/leakage_check.json\n")
if B:
    L.append(f"## Compute\nGlobal {B['global_seconds']/3600:.2f} h of {B['global_ceiling_h']} h; per cycle: " +
             ", ".join(f"c{k} {v/3600:.2f} h" for k, v in B["per_cycle"].items()) + " (state/budget.json)\n")
L.append("## Gates, novelty score, limitations\nSee HANDOFF.md (gate table) and state/novelty_ledger.json (scores); limitations in journal/ENTRIES.\n")
(R / "RESULTS_SUMMARY.md").write_text("\n".join(L))
print("\n".join(L))
